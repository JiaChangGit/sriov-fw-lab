#!/usr/bin/env python3
"""Generate shared MMIO constants from the versioned contract; --check is offline."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(schema):
    lines = ["/* Generated by tools/gen_abi.py from spec/abi.json. */",
             "#ifndef TOY_REGS_H", "#define TOY_REGS_H", ""]
    def define(name, value):
        lines.append(f"#define TOY_{name} 0x{value:x}u")
    define("ABI_VERSION", schema["abi"]["major"] << 16 | schema["abi"]["minor"])
    define("PF_MAGIC_VALUE", 0x5352494f)
    define("VF_MAGIC_VALUE", 0x56465249)
    define("GLOBAL", 0xffff)
    for group in ("pci", "limits", "statuses", "opcodes", "states", "features", "hw_flags",
                  "pf_events", "pf_control", "vf_hw_control", "mbx_status", "queue_status",
                  "last_fault", "sq_ops", "vf_irq"):
        for name, value in schema[group].items():
            define(group.upper() + "_" + name.upper(), value)
    for group, entries in schema["registers"].items():
        seen = set()
        for name, offset, access in entries:
            if offset % 4 or offset in seen or access not in {"RO", "RW", "W1", "RO_W1C"}:
                raise ValueError("Invalid register schema")
            seen.add(offset)
            define(group.upper() + "_" + name, offset)
    for name, value in schema["pf_vf_view"].items():
        define("PF_VF_" + name.upper(), value)
    for name, value in schema["capsule_stage"].items():
        define("CAPSULE_STAGE_" + name.upper(), value)
    for kind in ("sq", "cq"):
        coverage = set()
        for name, (offset, length) in schema[kind].items():
            fields = set(range(offset, offset + length))
            if coverage.intersection(fields):
                raise ValueError("Overlapping descriptor fields")
            coverage.update(fields)
            define(kind.upper() + "_" + name.upper() + "_OFFSET", offset)
        if coverage != set(range(32)):
            raise ValueError("Descriptor must cover exactly 32 bytes")
    lines.extend(["", "#define TOY_VF_VIEW(vf, reg) (TOY_PF_VF_BASE + (vf) * TOY_PF_VF_STRIDE + (reg))",
                  "", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "include/toy_regs.h"
    expected = render(json.loads((ROOT / "spec/abi.json").read_text()))
    if args.check:
        if not output.exists() or output.read_text() != expected:
            raise SystemExit("ABI header missing or differs from canonical schema")
        print("ABI_SCHEMA=PASS")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected)
        print(output)


if __name__ == "__main__":
    main()
